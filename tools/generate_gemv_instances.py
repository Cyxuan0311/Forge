#!/usr/bin/env python3
"""Generate src/operators/cuda/cuda_gemv_instances.cu from kernel_manifest.yaml.

kernel_manifest.yaml is the SINGLE SOURCE OF TRUTH for the quantized GEMV
dispatch tables. This script only renders it into C++.

Why this exists
---------------
Before the manifest, the dispatch table existed twice:

  A. src/operators/cuda/cuda_gemv_instances.cu  (hand-maintained, actually compiled)
  B. tools/generate_gemv_instances.py            (generator template, long stale)

(B) still pointed Q4_0 at `launch_gemv_q4_0_transB` (the retired scalar
smem/splitK kernel) while (A) had already moved Q4_0 to
`launch_gemv_q4_0_q8_1` (Q8_1 + dp4a). Re-running the old generator would
have silently reverted 15 of 16 quantized dtypes to the slow path.

Usage
-----
    # Regenerate cuda_gemv_instances.cu (run after editing kernel_manifest.yaml)
    python tools/generate_gemv_instances.py

    # CI / pre-commit: fail if the generated file is out of date
    python tools/generate_gemv_instances.py --check

Requires PyYAML (dev-only dependency).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.exit(
        "error: PyYAML is required to run this generator.\n"
        "       pip install PyYAML     (dev-only, not needed to build Forge)"
    )

REPO_ROOT = Path(__file__).resolve().parent.parent
MANIFEST = REPO_ROOT / "src" / "operators" / "cuda" / "kernel_manifest.yaml"
OUTPUT = REPO_ROOT / "src" / "operators" / "cuda" / "cuda_gemv_instances.cu"

HEADER = """\
// ============================================================================
// AUTO-GENERATED FILE — DO NOT EDIT
// ============================================================================
// Generated by tools/generate_gemv_instances.py from kernel_manifest.yaml.
//
// To change the dispatch tables, edit kernel_manifest.yaml and re-run:
//     python tools/generate_gemv_instances.py
//
// CI enforces that this file matches the manifest via:
//     python tools/generate_gemv_instances.py --check
// ============================================================================

// Explicit template instantiations for typed GEMV kernels + dispatch tables.
//
// The dispatch tables are indexed by forge::DataType enum value
// (see include/forge/types.h). A nullptr entry means that dtype has no
// dedicated CUDA GEMV kernel; callers fall back to device dequantization
// or report a capability failure (see matmul_cuda.cpp).

#include "cuda_gemv_tmpl.cuh"
#include "cuda_gemv.h"

namespace forge {
namespace cuda {

// ============================================================================
// Explicit template instantiation macros
//
// These instantiate the GENERIC templated kernels, which compute the dot
// product via CudaQuantTraits<DT>::dot_block() -- a per-element scalar
// implementation (cuda_gemv_tmpl.cuh). They are NOT the production path:
// the dispatch tables below prefer the specialized Q8_1 + dp4a kernels.
//
// The generic instantiations are retained as:
//   - a reference/correctness baseline when bringing up a new quantized dtype
//   - the implementation used by MoE expert GEMV (cuda_moe.cu)
// ============================================================================

#define INST_GEMV(DT)                                                       \\
    template void launch_gemv_typed_transB<DT>(                             \\
        const float*, const void*, float*, int, int, cudaStream_t);         \\
    template void launch_gemv_typed_transB_batch<DT>(                       \\
        const float*, const void*, float*, int, int, int, cudaStream_t);

@INST_LIST@

#undef INST_GEMV

// ============================================================================
// Function pointer dispatch tables
// Indexed by DataType enum value. nullptr for unsupported types.
// ============================================================================
"""

FOOTER = """
}  // namespace cuda
}  // namespace forge
"""


def render_table(table_name: str, fn_type: str, entries: list[dict], key: str) -> str:
    """Render one dispatch table with comment alignment."""
    cells: list[str] = []
    notes: list[str] = []

    for e in entries:
        fn = e.get(key) or "nullptr"
        cells.append(f"    /* {e['name']}={e['i']} */ {fn},")
        notes.append(e.get("note") or "")

    width = max(len(c) for c in cells) + 2

    lines = [f"const {fn_type} {table_name}[{len(entries)}] = {{"]
    for cell, note in zip(cells, notes):
        if note:
            lines.append(f"{cell.ljust(width)}// {note}")
        else:
            lines.append(cell)
    lines.append("};")
    return "\n".join(lines)


def validate(manifest: dict) -> list[str]:
    """Structural checks on the manifest. Returns a list of error strings."""
    errors: list[str] = []

    dispatch = manifest.get("dispatch")
    if not dispatch:
        return ["manifest is missing the 'dispatch' list"]

    seen: set[int] = set()
    for pos, e in enumerate(dispatch):
        label = f"dispatch[{pos}]"
        for field in ("i", "name"):
            if field not in e:
                errors.append(f"{label}: missing required field '{field}'")
        idx = e.get("i")
        if not isinstance(idx, int):
            errors.append(f"{label}: 'i' must be an integer, got {idx!r}")
            continue
        if idx in seen:
            errors.append(f"{label}: duplicate enum index {idx}")
        seen.add(idx)
        if idx != pos:
            errors.append(
                f"{label}: enum index {idx} does not match list position {pos}; "
                "entries must be ordered by DataType enum value"
            )
        # A dtype may legitimately have neither kernel (e.g. FP32, INT8), but
        # having one without the other is almost always a mistake.
        has_gemv = bool(e.get("gemv"))
        has_batch = bool(e.get("batch"))
        if has_gemv != has_batch:
            errors.append(
                f"{label} ({e.get('name')}): only one of gemv/batch is set "
                f"(gemv={e.get('gemv')!r}, batch={e.get('batch')!r})"
            )

    expected = list(range(len(dispatch)))
    if sorted(seen) != expected:
        errors.append(
            f"dispatch indices are not a contiguous 0..{len(dispatch) - 1} range: "
            f"{sorted(seen)}"
        )

    for t in manifest.get("template_instances", []):
        names = {e.get("name") for e in dispatch}
        if t not in names:
            errors.append(f"template_instances: '{t}' is not a known DataType name")

    return errors


def render(manifest: dict) -> str:
    inst_list = "\n".join(
        f"INST_GEMV(DataType::{t})" for t in manifest.get("template_instances", [])
    )
    entries = manifest["dispatch"]

    parts = [
        # NB: str.replace, not str.format -- HEADER is full of C++ braces.
        HEADER.replace("@INST_LIST@", inst_list),
        "",
        render_table("gemv_dispatch", "GemvFn", entries, "gemv"),
        "",
        render_table("gemv_batch_dispatch", "GemvBatchFn", entries, "batch"),
        "",
        FOOTER,
    ]
    return "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit non-zero if the generated file differs",
    )
    args = parser.parse_args()

    if not MANIFEST.is_file():
        print(f"error: manifest not found at {MANIFEST}", file=sys.stderr)
        return 1

    with MANIFEST.open(encoding="utf-8") as f:
        manifest = yaml.safe_load(f)

    errors = validate(manifest)
    if errors:
        print(f"error: {MANIFEST.name} is invalid:", file=sys.stderr)
        for e in errors:
            print(f"  - {e}", file=sys.stderr)
        return 1

    content = render(manifest)

    if args.check:
        if not OUTPUT.is_file():
            print(f"error: {OUTPUT} does not exist; run the generator", file=sys.stderr)
            return 1
        current = OUTPUT.read_text(encoding="utf-8")
        if current == content:
            print(f"ok: {OUTPUT.name} is up to date")
            return 0
        print(
            f"error: {OUTPUT.name} is out of date relative to {MANIFEST.name}.\n"
            f"       Re-run: python tools/generate_gemv_instances.py",
            file=sys.stderr,
        )
        return 1

    OUTPUT.write_text(content, encoding="utf-8")
    n = len(manifest["dispatch"])
    print(f"Generated {OUTPUT.relative_to(REPO_ROOT)} ({n} dispatch entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
